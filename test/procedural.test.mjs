test('scene-list CSV parsing and activity segmentation produce bounded beats', async () => {
  assert.deepEqual(parseSceneListCsv('Scene Number,Start Frame,End Frame\n1,0,29\n2,30,59\n'), [
    { startFrame: 0, endFrame: 29 }, { startFrame: 30, endFrame: 59 }
  ]);
  assert.deepEqual(parseSceneListCsv('nonsense\n'), []);

  const activity = new Array(40).fill(0.001);
  activity[20] = 0.9;
  const beats = segmentFromActivity(activity, { frameCount: 40 });
  assert.equal(beats.length, 2);
  assert.equal(beats[0].inFrame, 0);
  assert.equal(beats[0].outFrame, 19);
  assert.equal(beats[1].inFrame, 20);
  assert.equal(beats[1].outFrame, 39);
  assert.equal(beats[1].cutType, 'hard-cut');
  assert.equal(beats[1].peakFrame, 20);

  const directory = await fs.mkdtemp(path.join(work, 'beats-'));
  const fixture = path.join(directory, 'activity.json');
  await fs.writeFile(fixture, JSON.stringify({ frameCount: 40, activity }), 'utf8');
  const result = await segmentBeats(fixture);
  assert.equal(result.source, 'activity');
  assert.equal(result.beats.length, 2);
  assert.equal(result.beats[1].inFrame, 20);
  assert.ok(Number.isInteger(result.beats[0].settleFrame));
});

test('fingerprints feed the pure-JavaScript cut fallback when the detector is absent', async () => {
  const directory = await fs.mkdtemp(path.join(work, 'fallback-'));
  const blue = new PNG({ width: 8, height: 8 });
  blue.data.fill(20);
  const red = new PNG({ width: 8, height: 8 });
  red.data.fill(220);
  const fingerprints = Array.from({ length: 12 }, (_, frame) => {
    const png = frame < 6 ? blue : red;
    return fingerprintPng(PNG.sync.write(png));
  });
  const activity = activityFromFingerprints(fingerprints);
  assert.ok(activity[6] > activity[1]);

  const fixture = path.join(directory, 'fingerprints.json');
  await fs.writeFile(fixture, JSON.stringify({ frameCount: 12, fingerprints }), 'utf8');
  const result = await segmentBeats(fixture, { threshold: 0.05, minBeatFrames: 2 });
  assert.equal(result.source, 'fingerprint-fallback');
  assert.equal(result.beats.length, 2);
  assert.equal(result.beats[1].inFrame, 6);

  const video = path.join(directory, 'clip.mov');
  await fs.writeFile(video, '', 'utf8');
  const absent = await segmentBeats(video, { sceneDetector: { command: 'refclone-no-such-scene-detector' } });
  assert.equal(absent.source, 'fallback');
  assert.equal(absent.beats.length, 1);
  assert.ok(absent.limitations.some(line => /scene detector|PySceneDetect|ENOENT|not found/i.test(line)));
});

test('SVG stripping keeps geometry only and deduplicates paths', () => {
  const svg = `<?xml version="1.0"?>
    <!-- generated by a tool nobody should pay tokens for -->
    <svg width="64" height="32" xmlns="http://www.w3.org/2000/svg">
      <metadata><rdf:RDF>noise</rdf:RDF></metadata>
      <title>Mark</title><desc>a mark</desc>
      <path d="M 0 0 L 10 0 L 10 10 Z" fill="#ff0000"/>
      <path d="M 0 0 L 10 0 L 10 10 Z" fill="#ff0000"/>
      <path d="M 1 1 L 2 2" fill="#00ff00"/>
    </svg>`;
  const stripped = stripSvgMetadata(svg);
  assert.equal(stripped.viewBox, '0 0 64 32');
  assert.equal(stripped.paths.length, 2);
  assert.equal(stripped.d.includes('M 0 0 L 10 0 L 10 10 Z'), true);
  assert.equal(stripped.svg.includes('metadata'), false);
  assert.equal(stripped.svg.includes('title'), false);
  assert.equal(stripped.svg.includes('desc'), false);
  assert.equal(stripped.svg.includes('<!--'), false);
  assert.ok(stripped.removedBytes > 0);
  assert.deepEqual(stripSvgMetadata(''), { svg: '', paths: [], d: '', removedBytes: 0, viewBox: null });
});

test('VTracer converts a raster crop into a compact editable spline path', async () => {
  const directory = await fs.mkdtemp(path.join(work, 'trace-'));
  const png = new PNG({ width: 64, height: 64 });
  png.data.fill(255);
  for (let y = 16; y < 48; y += 1) for (let x = 16; x < 48; x += 1) {
    const at = (y * png.width + x) * 4;
    png.data[at] = 200; png.data[at + 1] = 20; png.data[at + 2] = 20; png.data[at + 3] = 255;
  }
  const crop = path.join(directory, 'crop.png');
  await fs.writeFile(crop, PNG.sync.write(png));
  const vector = await extractVector(crop);
  assert.equal(vector.available, true, vector.error);
  assert.ok(vector.paths.length >= 1);
  assert.match(vector.d, /^M/);
  assert.equal(vector.svg.includes('<path'), true);
  assert.equal(vector.svg.includes('metadata'), false);
  assert.ok(vector.tokenEstimate > 0);
  await assert.rejects(extractVector({ buffer: Buffer.alloc(0) }), error => error.code === 'VECTOR_CROP_INVALID');
  const missing = await extractVector(path.join(directory, 'missing.png'));
  assert.equal(missing.available, false);
  assert.match(missing.error, /not readable/i);
});

test('Savitzky-Golay smoothing removes jitter without inventing track endpoints', () => {
  const weights = savitzkyGolayWeights(5, 2);
  const expected = [-3 / 35, 12 / 35, 17 / 35, 12 / 35, -3 / 35];
  weights.forEach((weight, index) => assert.ok(Math.abs(weight - expected[index]) < 1e-12));

  const rows = Array.from({ length: 31 }, (_, frame) => [
    frame, 100 + 2 * frame + (frame % 2 ? 6 : -6), 50, 1, 0, 100
  ]);
  const smoothed = smoothRows(rows, { window: 7, order: 2 });
  assert.equal(smoothed.length, rows.length);
  assert.equal(smoothed[0][1], rows[0][1]);
  assert.equal(smoothed[smoothed.length - 1][1], rows[rows.length - 1][1]);
  const centre = 15;
  assert.ok(Math.abs(smoothed[centre][1] - (100 + 2 * centre)) < 3, `residual ${smoothed[centre][1]}`);
  assert.ok(Math.abs(smoothed[centre][1] - rows[centre][1]) < 6);
  assert.equal(rowVelocities(rows.slice(0, 2))[1], 14);
});

