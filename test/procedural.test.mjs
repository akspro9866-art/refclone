test('promotion recovers native presets and a custom cubic timing curve', () => {
  const expo = BezierEasing(0.16, 1, 0.3, 1);
  const expoPoints = Array.from({ length: 25 }, (_, index) => {
    const t = index / 24;
    return [t, expo(t)];
  });
  const expoFit = classifyEasing(expoPoints);
  assert.equal(expoFit.kind, 'preset');
  assert.equal(expoFit.name, 'ExpoOut');
  assert.ok(expoFit.score < 0.001);

  const back = BezierEasing(0.34, 1.56, 0.64, 1);
  const backFit = classifyEasing(Array.from({ length: 25 }, (_, index) => [index / 24, back(index / 24)]));
  assert.equal(backFit.kind, 'preset');
  assert.equal(backFit.name, 'BackOut');

  const odd = BezierEasing(0.9, -0.6, 0.1, 1.6);
  const oddFit = classifyEasing(Array.from({ length: 25 }, (_, index) => [index / 24, odd(index / 24)]));
  assert.equal(oddFit.kind, 'bezier');
  assert.equal(oddFit.handles.length, 4);
  assert.ok(oddFit.handles.every(Number.isFinite));
  assert.ok(oddFit.score < 0.2);
});

test('the ten-layer fixture promotes to one five-member stagger group under budget', async () => {
  const directory = await fs.mkdtemp(path.join(work, 'promote-'));
  const fixture = await writeFixture(directory, syntheticScene());
  const segmentation = await segmentBeats(fixture);
  assert.deepEqual(segmentation.beats.map(beat => [beat.inFrame, beat.outFrame]), SYNTHETIC_BEATS.map(beat => [beat.inFrame, beat.outFrame]));

  const promotion = promoteTracks(syntheticScene(), { beats: segmentation.beats, maxError: 2 });
  assert.equal(promotion.layers.length, 10);
  assert.equal(promotion.stats.inputSamples, 910);
  assert.ok(promotion.stats.reductionPct > 85, `reduction ${promotion.stats.reductionPct}`);
  assert.ok(promotion.stats.promotedKeyframes < promotion.stats.inputSamples * 0.1);
  assert.equal(promotion.groups.length, 1);
  const [group] = promotion.groups;
  assert.equal(group.members, 5);
  assert.equal(group.delayFrames, 3);
  assert.equal(group.attr, 'position.y');
  assert.equal(group.leaderId, 'word-0');
  assert.deepEqual(group.memberIds, ['word-0', 'word-1', 'word-2', 'word-3', 'word-4']);

  const followers = promotion.layers.filter(layer => layer.group === group.id);
  assert.equal(followers.length, 4);
  for (const layer of followers) assert.equal(layer.moves.some(move => move.attr === 'position.y'), false);
  for (const layer of promotion.layers) {
    for (const move of layer.moves) {
      assert.ok(move.outFrame > move.inFrame, `${layer.id} ${move.attr}`);
      assert.notEqual(move.from, move.to);
      assert.ok(['preset', 'bezier'].includes(move.easing.kind));
    }
  }
  const leader = promotion.layers.find(layer => layer.id === 'word-0');
  assert.equal(leader.moves.length, 1);
  assert.equal(leader.moves[0].attr, 'position.y');
  assert.ok(Math.abs(evaluateLayerAt(leader, 0).position.y - 240) < 1);
  assert.ok(evaluateLayerAt(leader, leader.moves[0].outFrame).position.y < 170);
});

test('promotion skips sub-epsilon drift and splits a pulse into two settled moves', () => {
  const jitter = {
    tracks: [{
      id: 'quiet', frames: Array.from({ length: 11 }, (_, frame) => [frame, 100 + (frame % 2 ? 0.2 : -0.2), 50, 1, 0, 100])
    }]
  };
  const quiet = promoteTracks(jitter, { beats: [{ beatIndex: 0, inFrame: 0, outFrame: 10 }] });
  assert.equal(quiet.layers.length, 0);

  const pulse = promoteTracks({
    tracks: [{
      id: 'flash', frames: Array.from({ length: 21 }, (_, frame) => [frame, 10, 20, 1, 0, frame <= 10 ? frame * 10 : (20 - frame) * 10])
    }]
  }, { beats: [{ beatIndex: 0, inFrame: 0, outFrame: 20 }], stagger: false });
  assert.equal(pulse.layers.length, 1);
  const moves = pulse.layers[0].moves.filter(move => move.attr === 'opacity');
  assert.equal(moves.length, 2);
  assert.equal(moves[0].inFrame, 0);
  assert.equal(moves[0].outFrame, 10);
  assert.equal(moves[0].from, 0);
  assert.equal(moves[0].to, 100);
  assert.equal(moves[1].from, 100);
  assert.equal(moves[1].to, 0);
});

test('fit-curve segment counts respond to maxError without emitting a frame table', () => {
  const rows = Array.from({ length: 31 }, (_, frame) => [frame, 0 + 100 * BezierEasing(0.16, 1, 0.3, 1)(frame / 30), 0, 1, 0, 100]);
  const property = { index: 1, attr: 'position.x', places: 1, epsilon: 0.5 };
  const coarse = promoteMove(rows, 0, 30, property, { maxError: 20 });
  const fine = promoteMove(rows, 0, 30, property, { maxError: 0.05 });
  assert.ok(coarse.fit.segments >= 1);
  assert.ok(fine.fit.segments >= coarse.fit.segments);
  assert.equal(coarse.from, 0);
  assert.equal(coarse.to, 100);
  assert.equal(Array.isArray(coarse.profile), true);
  assert.equal(coarse.profile.length, 9);
});

test('beat targeting ranks every active layer, caps the batch and keeps group followers relative', () => {
  const beats = SYNTHETIC_BEATS.map((beat, beatIndex) => ({ beatIndex, ...beat }));
  const promotion = promoteTracks(syntheticScene(), { beats, maxError: 2 });

  // Beat 0: one leader plus four staggered followers all rise inside the window;
  // the default cap keeps the first four in scene order.
  const beat0 = layersForBeat(promotion.beats[0], promotion);
  assert.deepEqual(beat0.map(target => target.layerId), ['word-0', 'word-1', 'word-2', 'word-3']);
  assert.equal(beat0[0].primary, true);
  assert.equal(beat0[0].expectedKnown, true);
  assert.ok(Math.abs(beat0[0].expected.position.x - 80) < 0.01);
  assert.ok(Math.abs(beat0[0].expected.position.y - 160.5) < 5, `y ${beat0[0].expected.position.y}`);
  for (const follower of beat0.slice(1)) {
    // The group rule moves them at a frame the promoted layer cannot evaluate,
    // so the gate must send a relative delta, never an absolute pose.
    assert.equal(follower.expectedKnown, false);
    assert.equal(follower.groupId, 'stagger-1');
    assert.equal(follower.expected, null);
  }
  assert.equal(beat0.every(target => target.frame === 12), true);

  // A cap of one is the legacy single-layer helper, byte for byte.
  const primary = layerForBeat(promotion.beats[0], promotion);
  assert.equal(primary.layerId, 'word-0');
  assert.equal(layersForBeat(promotion.beats[0], promotion, { maxLayersPerBeat: 1 }).length, 1);
  assert.throws(() => layersForBeat(promotion.beats[0], promotion, { maxLayersPerBeat: 0 }),
    error => error.code === 'PROCEDURAL_OPTIONS_INVALID');
  assert.deepEqual(layersForBeat(null, promotion), []);

  // Beat 1: mark translates, the discs scale. Raw displacement ranks mark first.
  const beat1 = layersForBeat(promotion.beats[1], promotion);
  assert.deepEqual(beat1.map(target => target.layerId), ['mark', 'disc-a', 'disc-b']);
  assert.equal(beat1[0].layerId, 'mark');
  assert.equal(beat1[0].basis, 'displacement');

  // With known per-layer boxes, overlap with the odiff mismatch region outranks amplitude.
  const layerBoxes = {
    mark: { x1: 200, y1: 50, x2: 300, y2: 120 },
    'disc-a': { x1: 100, y1: 60, x2: 140, y2: 100 },
    'disc-b': { x1: 210, y1: 60, x2: 250, y2: 100 }
  };
  const spatial = layersForBeat(promotion.beats[1], promotion, {
    mismatchBox: { x1: 205, y1: 50, x2: 260, y2: 120 }, layerBoxes
  });
  assert.equal(spatial[0].basis, 'mismatch-overlap');
  assert.equal(spatial[0].layerId, 'mark');
  assert.equal(spatial[0].overlap, 3850);
  assert.deepEqual(spatial.map(target => target.layerId), ['mark', 'disc-b', 'disc-a']);
});

test('the orchestrator compiles the fixture and refuses to overwrite artifacts', async () => {
  const directory = await fs.mkdtemp(path.join(work, 'orchestrate-'));
  const fixture = await writeFixture(directory);
  const result = await runProcedural(fixture, { dryRun: true });
  assert.equal(result.status, 'dry-run');
  assert.equal(result.layers, 10);
  assert.equal(result.groups.length, 1);
  assert.equal(result.frameBakedArrays, 0);
  assert.ok(result.tokenEstimate < TOKEN_BUDGET);
  assert.equal(result.gate, null);
  assert.equal(result.artifacts, null);
  assert.equal(frameBakedArrays(result.script), 0);

  const output = path.join(directory, 'out');
  const written = await runProcedural(fixture, { dryRun: true, outputDirectory: output });
  assert.ok(written.artifacts);
  const script = await fs.readFile(written.artifacts.scriptPath, 'utf8');
  assert.equal(script.trim(), result.script);
  const report = JSON.parse(await fs.readFile(written.artifacts.reportPath, 'utf8'));
  assert.equal(report.frameBakedArrays, 0);
  assert.equal(report.tokenEstimate, result.tokenEstimate);
  await assert.rejects(runProcedural(fixture, { dryRun: true, outputDirectory: output }),
    error => error.code === 'OUTPUT_EXISTS');
  await assert.rejects(runProcedural(fixture, { dryRun: true, threshold: 150 }),
    error => error.code === 'PROCEDURAL_OPTIONS_INVALID');
  await assert.rejects(runProcedural(fixture, { dryRun: true, maxPasses: 0 }),
    error => error.code === 'PROCEDURAL_OPTIONS_INVALID');

  // Stage 2A is part of the route: a crop listed beside the scene is traced and
  // attached to the track with the same id before promotion.
  const cropPng = new PNG({ width: 32, height: 32 });
  cropPng.data.fill(255);
  for (let y = 8; y < 24; y += 1) for (let x = 8; x < 24; x += 1) {
    const at = (y * cropPng.width + x) * 4;
    cropPng.data[at] = 30; cropPng.data[at + 1] = 90; cropPng.data[at + 2] = 200; cropPng.data[at + 3] = 255;
  }
  await fs.writeFile(path.join(directory, 'crop.png'), PNG.sync.write(cropPng));
  const vectorScene = {
    width: 320, height: 180, fps: 30, endFrame: 30,
    crops: [{ id: 'mark', path: 'crop.png' }],
    tracks: [{
      id: 'mark', name: 'Mark', type: 'svg',
      frames: Array.from({ length: 31 }, (_, frame) => [frame, 100 + frame * 4, 50, 1, 0, 100])
    }]
  };
  const vectorFixture = path.join(directory, 'vector-scene.json');
  await fs.writeFile(vectorFixture, JSON.stringify(vectorScene), 'utf8');
  const traced = await runProcedural(vectorFixture, { dryRun: true });
  assert.equal(traced.vectors.available, true);
  assert.equal(traced.vectors.count, 1);
  assert.equal(traced.vectors.traced, 1);
  assert.deepEqual(traced.vectors.errors, []);
  assert.ok(Number.isFinite(traced.vectors.removedBytes));
  assert.match(traced.script, /_mg\.svg\(/);
  assert.match(traced.script, /"d":"M/);
});

